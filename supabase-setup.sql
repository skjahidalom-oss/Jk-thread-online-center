create table if not exists public.notices (
  id bigint generated by default as identity primary key,
  title text not null,
  body text not null,
  published boolean not null default false,
  created_by uuid not null references auth.users(id),
  created_at timestamptz not null default now()
);

alter table public.notices enable row level security;

-- সবাই শুধু প্রকাশিত নোটিশ পড়তে পারবে।
drop policy if exists "Public can read published notices" on public.notices;
create policy "Public can read published notices"
on public.notices for select
to anon, authenticated
using (published = true);

-- লগইন করা অ্যাডমিন নিজের user ID দিয়ে নোটিশ যোগ করতে পারবে।
drop policy if exists "Signed-in users can create notices as themselves" on public.notices;
create policy "Signed-in users can create notices as themselves"
on public.notices for insert
to authenticated
with check (auth.uid() = created_by);

-- শুধু যে অ্যাডমিন নোটিশ তৈরি করেছে সে সেটি মুছতে পারবে।
drop policy if exists "Authors can delete their notices" on public.notices;
create policy "Authors can delete their notices"
on public.notices for delete
to authenticated
using (auth.uid() = created_by);
